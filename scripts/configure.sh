#!/usr/bin/env bash
# scripts/configure.sh - 환경 탐색 및 동적 변수 생성 (기존 check-deps.sh 대체)
#
# OS(Mac/Linux/Windows), 패키지 매니저(brew, apt 등), Docker 환경을
# 동적으로 탐지하여 .cockpit-local/.cockpit-env 파일을 생성합니다.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

# 공통 라이브러리는 필수 — 로드 실패는 silent fallback 없이 즉시 실패한다 (brain/philosophy.md § fail-closed)
# shellcheck source=scripts/lib/common.sh
. "$SCRIPT_DIR/lib/common.sh"
# shellcheck source=scripts/lib/tui.sh
. "$SCRIPT_DIR/lib/tui.sh"

detect_os_and_package_manager() {
	OS_TYPE="$(uname -s)"
	ARCH_TYPE="$(uname -m)"
	DOCKER_CMD="docker"
	# 실제로 설치된 매니저만 채택 (macOS 라도 Homebrew 가 없으면 빈 값)
	PKG_MANAGER="$(detect_package_manager)"
	# 이미 쓰는 런타임(Docker Desktop·OrbStack·Colima·네이티브 등)을 그대로 존중
	DOCKER_RUNTIME="$(detect_docker_runtime)"
	USER_SHELL="$(basename "${SHELL:-sh}")"
	# Colima 는 "macOS 에 Docker 런타임이 아예 없을 때"의 권장 기본값일 뿐 강제하지 않음
	NEEDS_COLIMA="false"
	if [ "$OS_TYPE" = "Darwin" ] && [ "$DOCKER_RUNTIME" = "none" ]; then
		NEEDS_COLIMA="true"
	fi

	printf "  \033[2m· OS: %s\033[0m\n" "$OS_TYPE"
	printf "  \033[2m· Arch: %s\033[0m\n" "$ARCH_TYPE"
	printf "  \033[2m· Package Manager: %s\033[0m\n" "${PKG_MANAGER:-없음}"
	printf "  \033[2m· Docker Runtime: %s\033[0m\n" "$DOCKER_RUNTIME"
	printf "  \033[2m· Shell: %s\033[0m\n" "$USER_SHELL"
}

export_environment_variables() {
	local LOCAL_DIR="$ROOT_DIR/.cockpit-local"
	mkdir -p "$LOCAL_DIR"
	local ENV_FILE="$LOCAL_DIR/.cockpit-env"
	local managed='^export (OS_TYPE|ARCH_TYPE|PKG_MANAGER|DOCKER_CMD|DOCKER_RUNTIME|NEEDS_COLIMA|USER_SHELL)='

	# 다른 단계가 추가한 값(예: global-install 의 COCKPIT_LANG)은 단독 재실행 시에도 보존
	local preserved=""
	if [ -f "$ENV_FILE" ]; then
		preserved="$(grep -E '^export [A-Z_]+=' "$ENV_FILE" | grep -Ev "$managed" || true)"
	fi

	{
		echo "# 🚀 Auto-generated by configure.sh (do not edit manually unless needed)"
		echo "export OS_TYPE=\"$OS_TYPE\""
		echo "export ARCH_TYPE=\"$ARCH_TYPE\""
		echo "export PKG_MANAGER=\"$PKG_MANAGER\""
		echo "export DOCKER_CMD=\"$DOCKER_CMD\""
		echo "export DOCKER_RUNTIME=\"$DOCKER_RUNTIME\""
		echo "export NEEDS_COLIMA=\"$NEEDS_COLIMA\""
		echo "export USER_SHELL=\"$USER_SHELL\""
		[ -z "$preserved" ] || printf '%s\n' "$preserved"
	} >"$ENV_FILE"

	printf "  \033[32m✓\033[0m 환경 변수 생성 완료: %s\n\n" "$ENV_FILE"
}

check_req() {
	if ! command -v "$1" >/dev/null 2>&1; then
		MISSING_PKGS+=("$1")
	else
		printf "  \033[32m✓\033[0m 필수 도구 확인: %s\n" "$1"
	fi
}

print_package_manager_hint() {
	case "$OS_TYPE" in
	Darwin) printf "    Homebrew 설치: https://brew.sh 후 재실행하거나, 직접 설치하세요.\n" ;;
	Linux) printf "    배포판 패키지 매니저(apt·dnf·pacman·zypper·apk 등)로 직접 설치하세요.\n" ;;
	*) printf "    해당 OS 의 패키지 매니저로 직접 설치하세요.\n" ;;
	esac
}

install_missing_required_packages() {
	MISSING_PKGS=()
	printf "  \033[34m→\033[0m 필수 도구 검증\n"
	check_req "git"
	check_req "jq"
	check_req "curl"

	[ ${#MISSING_PKGS[@]} -gt 0 ] || return 0

	if [ -z "$PKG_MANAGER" ]; then
		printf "  \033[31m✗\033[0m 필수 패키지가 없으며 패키지 매니저를 감지할 수 없습니다: %s\n" "${MISSING_PKGS[*]}"
		print_package_manager_hint
		exit 1
	fi

	printf "  \033[33m⚠\033[0m 필수 패키지가 누락되었습니다: %s\n" "${MISSING_PKGS[*]}"
	printf "  \033[34m→\033[0m 자동 설치를 시도합니다 (%s)...\n" "$PKG_MANAGER"
	if ! pkg_install "${MISSING_PKGS[@]}"; then
		printf "  \033[31m✗\033[0m 자동 설치 실패 (%s): %s\n" "$PKG_MANAGER" "${MISSING_PKGS[*]}"
		print_package_manager_hint
		exit 1
	fi
}

# Docker 런타임은 MCP 서버에만 필요하므로 여기서 자동 설치하지 않습니다.
# (MCP 설치 단계 setup.sh 가 사용자 확인을 받고 처리)
report_docker_runtime() {
	case "$DOCKER_RUNTIME" in
	none)
		if [ "$NEEDS_COLIMA" = "true" ]; then
			printf "  \033[33m○\033[0m Docker 런타임 없음 — MCP 설치 시 Colima 설치를 제안합니다 (이미 쓰는 런타임이 있다면 먼저 설치·실행하세요)\n"
		else
			printf "  \033[33m○\033[0m Docker 런타임 없음 — MCP 서버를 쓰려면 docker 를 설치하세요\n"
		fi
		;;
	*)
		if docker_daemon_up; then
			printf "  \033[32m✓\033[0m Docker 런타임: %s (실행 중)\n" "$DOCKER_RUNTIME"
		else
			printf "  \033[33m○\033[0m Docker 런타임: %s (정지 상태 — MCP 사용 전 실행 필요)\n" "$DOCKER_RUNTIME"
		fi
		;;
	esac
}

check_rec() {
	if ! command -v "$1" >/dev/null 2>&1; then
		printf "  \033[33m○\033[0m %-12s \033[2m(권장) %s\033[0m\n" "$1" "$2"
	else
		local ver
		ver="$("$1" --version 2>/dev/null | head -1 | cut -c 1-40 || echo '')"
		printf "  \033[32m✓\033[0m %-12s \033[2m%s\033[0m\n" "$1" "$ver"
	fi
}

run_doctor_checks() {
	printf "\n  \033[34m→\033[0m 권장 도구 진단 (Doctor - 부족해도 설치는 계속됩니다)\n"
	check_rec gh "GitHub 작업 전반"
	check_rec rg "ripgrep (초고속 검색)"
	check_rec fd "fd (초고속 파일 찾기)"
	check_rec bat "bat (cat 대체)"
	check_rec yq "yaml 파서"
	check_rec tree "디렉토리 구조 보기"
	check_rec shfmt "쉘 포맷터"
	check_rec shellcheck "쉘 정적 분석"
	check_rec python3 "Python 3 런타임"
	check_rec uv "초고속 Python 패키지 매니저"
	check_rec go "Go 컴파일러"
	check_rec ruff "Python 린터"
	check_rec biome "JS/TS 포맷터"
}

parse_arguments() {
	while [ $# -gt 0 ]; do
		case "$1" in
		-h | --help)
			cat <<EOF
Usage: $0

OS·패키지 매니저·Docker 환경을 탐지해 .cockpit-local/.cockpit-env 를 생성합니다.
install.sh Phase 1 에서 호출되며, 단독 실행으로 환경 재진단만 할 수도 있습니다.

  · 필수 패키지 누락 시 설치 시도
  · Docker 런타임 감지만 수행 (Colima·Docker Desktop·OrbStack·네이티브 등 기존 런타임 존중, 자동 설치 없음)
  · 권장 도구 doctor 체크 (rg·fd·shellcheck 등)
EOF
			exit 0
			;;
		*) die "알 수 없는 옵션: $1" ;;
		esac
	done
}

main() {
	parse_arguments "$@"
	tui_banner "▸ Phase 1 · Configure (환경 진단 및 설정)"

	detect_os_and_package_manager
	export_environment_variables
	install_missing_required_packages
	report_docker_runtime
	run_doctor_checks

	printf "\n  \033[32m✓\033[0m Configure 완료. 환경이 준비되었습니다.\n"
}

main "$@"
